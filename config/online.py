"""
Конфигурация онлайн-системы (план docs/ONLINE_SYSTEM_PLAN.md, §7).

Все таймауты/пороги — в одном месте, не вразброс по коду.
Любое значение легко переопределить при создании OnlineConfig(...).
"""
from dataclasses import dataclass, asdict


@dataclass
class OnlineConfig:
    # =========================================================================
    # Tick-цикл
    # =========================================================================
    tick_seconds: float = 1.0          # частота данных (1 Гц)
    speed: float = 1.0                 # множитель скорости playback (<=0 = без пауз, «max»)

    # =========================================================================
    # «Память» (ADR-4): скользящее окно raw-строк
    # =========================================================================
    buffer_multiplier: int = 2         # maxlen = multiplier * max(seq_len, 600)

    # =========================================================================
    # Inference watchdog (план §7)
    # =========================================================================
    inference_timeout_s: float = 5.0   # таймаут одного вызова predict
    stale_pause_threshold: int = 3     # N подряд stale → источник на паузу

    # =========================================================================
    # WebSocket / UI (используется с ШАГА 3; значения фиксируются здесь же)
    # =========================================================================
    ws_send_timeout_s: float = 1.0

    # =========================================================================
    # Границы сессии (план §7)
    # =========================================================================
    max_session_hours: float = 24.0    # авто-stop live-сессии
    playback_speed_choices: tuple = (1.0, 5.0, 20.0, 100.0)

    # =========================================================================
    # Детекторы аномалий (ШАГ 2; значения фиксируются здесь же, план §6)
    # =========================================================================
    input_anomaly_z: float = 4.0       # порог |z| по признакам входа
    error_anomaly_k: float = 2.5       # порог rolling-MAE = k × (val MAE модели)
    error_window_ticks: int = 30       # окно rolling-MAE, сек
    hysteresis_consecutive: int = 2    # подряд срабатываний для смены статуса
    marker_cooldown_s: float = 10.0    # анти-дребезг смены статуса

    # =========================================================================
    # MC-Dropout (N4/C4): неопределённость прогноза + вход СППР «не верить прогнозу»
    # Валидация — results/mc_dropout_n4/ (2026-09-29): corr(std_MC, |error|) +0.6…0.9
    # (per-segment), покрытие ±1.96σ НИЖЕ номинала (0.3–0.7) → пороги «не верить» —
    # эмпирические (per-target, физ. ед.), НЕ номинальные z.
    # =========================================================================
    uncertain_cadence: int = 10        # MC-прогноз каждые N tick'ов (1/10, план C4)
    uncertain_mc_samples: int = 30     # число стохастических прогонов
    uncertain_ribbon_z: float = 1.96   # ширина ленты UI = z × std
    uncertain_max_std: dict = None     # пороги «не верить прогнозу» по целям (физ. ед.);
                                       # None = статус не вычисляется; рекомендуемые
                                       # значения — из results/mc_dropout_n4

    # =========================================================================
    # Дообучение (ADR-6; используется с ШАГА 5)
    # =========================================================================
    finetune_min_rows: int = 600       # минимум «уникальных» строк
    finetune_max_epochs: int = 20
    finetune_patience: int = 5
    finetune_wall_clock_minutes: float = 30.0
    finetune_cooldown_minutes: float = 60.0

    def to_dict(self) -> dict:
        return asdict(self)
